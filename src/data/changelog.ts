// 首页「更新内容」数据源（What's New）。
//
// 手动维护方式（唯一动作）：
//   每次发版时，在数组【最前面】追加一条对象，version 填本次发版号即可
//   （就是你已经使用的 git tag，如 1.2.69）。其余字段按需填写。
//   无需改动任何其他代码——前端会自动把最新一条展示给所有用户，
//   直到该用户在本浏览器点击「关闭」；关闭后记录该 version，
//   下次发版（version 增大）才会再次自动出现。
//
// 展示顺序：数组第一项（index 0）为「最新」，其余历史条目保留作归档。

export interface ChangelogEntry {
  /** 发版号，与 git tag 保持一致，如 "1.2.69" */
  version: string
  /** 发布日期 YYYY-MM-DD */
  date: string
  /** 本次更新标题，一句话概括 */
  title: string
  /** 更新要点列表（每条一句话） */
  items: string[]
}

