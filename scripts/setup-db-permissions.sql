-- =====================================================================
-- 数据库最小权限账号创建脚本（运维安全加固）
-- 用途：为 OA 系统创建"最小权限"应用账号，替代原来的全权限账号。
--       应用账号只具备日常读写所需权限，避免拥有 DDL/全局管理等高危权限。
-- 适用：MySQL 5.7 / 8.0（服务器、本机均可）
-- 使用：
--   1. 以 root 或具备 GRANT 权限的管理员账号执行本脚本
--   2. 将脚本中 qygl_app / 密码 / 数据库名 替换为实际值
--   3. 更新 .env 中 DB_USER / DB_PASSWORD 为新建的账号
-- =====================================================================

-- ① 创建应用账号（若已存在则重建，避免残留权限）
--    仅允许本机/内网连接；如需远程连接请把 'localhost' 替换为 '%'（谨慎）
DROP USER IF EXISTS 'qygl_app'@'localhost';

-- ② 创建账号，密码请替换为强随机值（可用 openssl rand -base64 24 生成）
CREATE USER 'qygl_app'@'localhost' IDENTIFIED BY '请替换为强随机密码';

-- ③ 授予该库的最小权限：增删改查（不含 DDL：CREATE/DROP/ALTER 等）
GRANT SELECT, INSERT, UPDATE, DELETE ON qyglfb.* TO 'qygl_app'@'localhost';

-- ④ 如需存储过程/函数执行权限（部分接口用到），再额外授予：
-- GRANT EXECUTE ON qyglfb.* TO 'qygl_app'@'localhost';

-- ⑤ 应用账号不应拥有 mysql.user 等系统表的任何权限（已默认不授予）

-- ⑥ 刷新权限
FLUSH PRIVILEGES;

-- =====================================================================
-- 验证：
--   SHOW GRANTS FOR 'qygl_app'@'localhost';
--   应只看到 SELECT/INSERT/UPDATE/DELETE（及可选 EXECUTE），无 CREATE/DROP/GRANT。
-- =====================================================================

